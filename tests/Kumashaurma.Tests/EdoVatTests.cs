using Kumashaurma.API.Services.Edo;
using Xunit;

namespace Kumashaurma.Tests
{
    public class EdoVatTests
    {
        // Как в настоящем УПД: сумма налога по строке в СумНал/СумНал, итог — в ВсегоОпл/СумНалВсего
        private const string UpdTwoRates = @"<Файл ИдФайл=""ON_NSCHFDOPPR_vat"" ВерсФорм=""5.03"">
  <Документ>
    <СвСчФакт НомерДок=""УТ-77"" ДатаДок=""21.10.2026"">
      <СвПрод><ИдСв><СвЮЛУч НаимОрг=""ООО Поставщик"" ИННЮЛ=""7700000000"" КПП=""770001001""/></ИдСв></СвПрод>
    </СвСчФакт>
    <ТаблСчФакт>
      <СведТов НомСтр=""1"" НаимТов=""Соус"" ОКЕИ_Тов=""796"" КолТов=""10"" ЦенаТов=""100"" СтТовБезНДС=""1000.00"" НалСт=""20%"" СтТовУчНал=""1200.00"">
        <Акциз><БезАкциз>без акциза</БезАкциз></Акциз>
        <СумНал><СумНал>200.00</СумНал></СумНал>
      </СведТов>
      <СведТов НомСтр=""2"" НаимТов=""Молоко"" ОКЕИ_Тов=""796"" КолТов=""12"" ЦенаТов=""80"" СтТовБезНДС=""960.00"" НалСт=""10%"" СтТовУчНал=""1056.00"">
        <СумНал><СумНал>96.00</СумНал></СумНал>
      </СведТов>
      <СведТов НомСтр=""3"" НаимТов=""Лаваш"" ОКЕИ_Тов=""796"" КолТов=""10"" ЦенаТов=""15"" СтТовБезНДС=""150.00"" НалСт=""без НДС"" СтТовУчНал=""150.00"">
        <СумНал><БезНДС>без НДС</БезНДС></СумНал>
      </СведТов>
      <ВсегоОпл СтТовБезНДСВсего=""2110.00"" СтТовУчНалВсего=""2406.00"">
        <СумНалВсего><СумНал>296.00</СумНал></СумНалВсего>
      </ВсегоОпл>
    </ТаблСчФакт>
  </Документ>
</Файл>";

        // Продавец на упрощёнке: все строки и итог «без НДС»
        private const string UpdWithoutVat = @"<Файл ИдФайл=""ON_NSCHFDOPPR_novat"" ВерсФорм=""5.03"">
  <Документ>
    <СвСчФакт НомерДок=""12"" ДатаДок=""01.10.2026"">
      <СвПрод><ИдСв><СвИП ИННФЛ=""500100732259""><ФИО Фамилия=""Иванов"" Имя=""Иван"" Отчество=""Иванович""/></СвИП></ИдСв></СвПрод>
    </СвСчФакт>
    <ТаблСчФакт>
      <СведТов НомСтр=""1"" НаимТов=""Лаваш"" ОКЕИ_Тов=""796"" КолТов=""1000"" ЦенаТов=""12.5"" СтТовБезНДС=""12500"" НалСт=""без НДС"" СтТовУчНал=""12500"">
        <СумНал><БезНДС>без НДС</БезНДС></СумНал>
      </СведТов>
      <ВсегоОпл СтТовУчНалВсего=""12500""><СумНалВсего><БезНДС>без НДС</БезНДС></СумНалВсего></ВсегоОпл>
    </ТаблСчФакт>
  </Документ>
</Файл>";

        // Нет блоков СумНал — только суммы с НДС и без (так тоже присылают)
        private const string UpdNoVatBlocks = @"<Файл ИдФайл=""ON_NSCHFDOPPR_diff"">
  <Документ>
    <СвСчФакт НомерСчФ=""5"" ДатаСчФ=""02.10.2026""/>
    <ТаблСчФакт>
      <СведТов НомСтр=""1"" НаимТов=""Сыр"" ОКЕИ_Тов=""166"" КолТов=""2"" ЦенаТов=""500"" СтТовБезНДС=""1000"" НалСт=""20%"" СтТовУчНал=""1200""/>
      <ВсегоОпл СтТовУчНалВсего=""1200""/>
    </ТаблСчФакт>
  </Документ>
</Файл>";

        [Fact]
        public void ParsesVatPerLineAndTotal()
        {
            var u = UpdParser.Parse(UpdTwoRates);

            Assert.Equal(296m, u.VatTotal);
            Assert.False(u.WithoutVat);
            Assert.Equal(new[] { 200m, 96m, 0m }, u.Lines.Select(l => l.Vat));
            Assert.Equal(new[] { false, false, true }, u.Lines.Select(l => l.WithoutVat));
        }

        [Fact]
        public void GroupsVatByRate_AndBuildsPaymentPurpose()
        {
            var u = UpdParser.Parse(UpdTwoRates);

            var groups = UpdParser.VatByRate(u);
            Assert.Equal(new[] { "20%", "10%" }, groups.Select(g => g.Rate));
            Assert.Equal(new[] { 200m, 96m }, groups.Select(g => g.Vat));

            Assert.Equal("в т.ч. НДС 20% — 200,00 руб., 10% — 96,00 руб.", UpdParser.VatPhrase(u));
            Assert.Equal(
                "Оплата по УПД № УТ-77 от 21.10.2026. Сумма 2 406,00 руб., в т.ч. НДС 20% — 200,00 руб., 10% — 96,00 руб.",
                UpdParser.PaymentPurpose(u));
        }

        [Fact]
        public void WholeDocumentWithoutVat()
        {
            var u = UpdParser.Parse(UpdWithoutVat);

            Assert.Equal(0m, u.VatTotal);
            Assert.True(u.WithoutVat);
            Assert.Empty(UpdParser.VatByRate(u));
            Assert.Equal("Оплата по УПД № 12 от 01.10.2026. Сумма 12 500,00 руб., НДС не облагается", UpdParser.PaymentPurpose(u));
        }

        [Fact]
        public void WithoutVatBlocks_VatIsDifferenceOfSums()
        {
            var u = UpdParser.Parse(UpdNoVatBlocks);

            Assert.Equal(200m, u.Lines[0].Vat);
            Assert.Equal(200m, u.VatTotal);
            Assert.Equal("в т.ч. НДС 20% — 200,00 руб.", UpdParser.VatPhrase(u));
        }
    }
}
